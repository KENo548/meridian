// Build lookup indices
const _byId = new Map(CATALOGUE.map(f => [f.id, f]))
const _byAlias = new Map()
for (const firm of CATALOGUE) {
  const allNames = [firm.canonicalName, ...firm.aliases].map(n => normalizeName(n))
  for (const name of allNames) {
    if (!_byAlias.has(name)) _byAlias.set(name, firm.id)
  }
}
const _byDomain = new Map()
for (const firm of CATALOGUE) {
  for (const d of firm.domains) {
    _byDomain.set(d.toLowerCase(), firm.id)
  }
}

function normalizeName(name) {
  return name.toLowerCase().replace(/[^a-z0-9\s]/g, '').replace(/\s+/g, ' ').trim()
}

function lookupById(id) {
  return _byId.get(id) || null
}

function lookupByAlias(companyName) {
  const norm = normalizeName(companyName)
  return _byAlias.get(norm) || null
}

function lookupByDomain(domain) {
  if (!domain) return null
  const norm = domain.toLowerCase().replace(/^www\./, '')
  return _byDomain.get(norm) || null
}

function lookupPartial(companyName) {
  const norm = normalizeName(companyName)
  for (const firm of CATALOGUE) {
    const allNames = [firm.canonicalName, ...firm.aliases].map(n => normalizeName(n))
    for (const name of allNames) {
      if (norm.includes(name) || name.includes(norm)) {
        return firm.id
      }
    }
  }
  return null
}

